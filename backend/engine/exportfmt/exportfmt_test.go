// extractEntry reads one entry of a zip archive as a string.
func extractEntry(t *testing.T, raw []byte, name string) string {
	t.Helper()
	r, err := zip.NewReader(bytes.NewReader(raw), int64(len(raw)))
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range r.File {
		if f.Name == name {
			src, err := f.Open()
			if err != nil {
				t.Fatal(err)
			}
			defer src.Close()
			content, err := io.ReadAll(src)
			if err != nil {
				t.Fatal(err)
			}
			return string(content)
		}
	}
	t.Fatalf("entry %q missing", name)
	return ""
}

// extractAllPDFText reads every page of a PDF with the import reader.
func extractAllPDFText(t *testing.T, raw []byte) string {
	t.Helper()
	reader, err := ledongthuc.NewReader(bytes.NewReader(raw), int64(len(raw)))
	if err != nil {
		t.Fatalf("generated PDF unreadable: %v", err)
	}
	var b strings.Builder
	for i := 1; i <= reader.NumPage(); i++ {
		page := reader.Page(i)
		if page.V.IsNull() {
			continue
		}
		if text, err := page.GetPlainText(nil); err == nil {
			b.WriteString(text)
			b.WriteString("\n")
		}
	}
	return b.String()
}

