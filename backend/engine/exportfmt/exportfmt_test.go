// zipEntryHashes maps entry name → content hash for passthrough checks.
func zipEntryHashes(t *testing.T, raw []byte) map[string]string {
	t.Helper()
	r, err := zip.NewReader(bytes.NewReader(raw), int64(len(raw)))
	if err != nil {
		t.Fatal(err)
	}
	out := map[string]string{}
	for _, f := range r.File {
		src, err := f.Open()
		if err != nil {
			t.Fatal(err)
		}
		content, err := io.ReadAll(src)
		src.Close()
		if err != nil {
			t.Fatal(err)
		}
		out[f.Name] = fmt.Sprintf("%x", sha256.Sum256(content))
	}
	return out
}

// buildZip assembles a small deterministic OOXML zip for bespoke fixtures.
func buildZip(t *testing.T, entries map[string]string) []byte {
	t.Helper()
	var names []string
	for n := range entries {
		names = append(names, n)
	}
	sort.Strings(names)
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	for _, n := range names {
		fh := &zip.FileHeader{Name: n, Method: zip.Deflate}
		fh.Modified = time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
		fw, err := w.CreateHeader(fh)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := fw.Write([]byte(entries[n])); err != nil {
			t.Fatal(err)
		}
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

