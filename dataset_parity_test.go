// dataset_parity_test.go — no camel-case data attribute anywhere in the frontend
//
// The bug this exists to prevent already happened once, and it produced seven
// dead controls on one card while every test stayed green.
//
// An HTML parser LOWER-CASES attribute names. A view that renders
// `data-mainText="Marie Duval"` therefore puts `data-maintext` into the DOM,
// whose `dataset` key is `maintext`, and every handler reading
// `dataset.mainText` gets `undefined`. Nothing throws: renaming a Value,
// removing it, dropping a spelling and merging two Values all silently did
// nothing. The frontend render tests could not see it either, because they
// assert the HTML STRING a view wrote and a string preserves whatever case the
// author typed.
//
// The DOM's own spelling is the dash form: `data-main-text` is read back as
// `dataset.mainText`. So this guard reads the frontend sources as text and fails
// on any `data-` attribute name carrying an upper-case letter, in either of the
// two ways this codebase emits one: a literal in a template string, and a key of
// the `data: {...}` option `ui.js button()` expands into attributes.
//
// frontend/identifyrail.test.js and frontend/identifyvalues.test.js assert the
// same rule locally, on their own output. Those stay: a local failure names the
// control, and this one names the file for a module nobody wrote a test for yet.
package main

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// dataAttrRe matches a rendered `data-*` attribute name, i.e. the literal form
// that reaches markup. The name may carry any letter case; whether it should is
// what this guard decides.
var dataAttrRe = regexp.MustCompile(`data-([A-Za-z][A-Za-z0-9-]*)\s*=`)

// dataOptionRe matches the body of a `data: { ... }` option object, the second
// route to a rendered attribute: ui.js button() writes `data-<key>` for every
// key it finds, so a camel-case key there is the same defect one level up.
var dataOptionRe = regexp.MustCompile(`(?s)\bdata:\s*\{(.*?)\}`)

// dataOptionKeyRe pulls the keys out of one such object body. Both spellings
// occur: a bare identifier (`spelling: v`) and a quoted key
// (`"group-type": type`), the latter being how a dashed name is written at all.
var dataOptionKeyRe = regexp.MustCompile(`(?:^|[{,\s])"?([A-Za-z][A-Za-z0-9_-]*)"?\s*:`)

// frontendSourceFiles lists every shipped frontend module, i.e. the .js files
// that are embedded in the binary. Test files are excluded: a test may quote a
// bad attribute on purpose to prove it is refused, and testdom.js's own doc
// comment names `data-mainText` to explain what it guards against.
func frontendSourceFiles(t *testing.T) []string {
	t.Helper()
	var files []string
	err := filepath.WalkDir("frontend", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			// wailsjs is GENERATED by `wails build` and gitignored; docs and
			// assets hold no rendering code.
			if d.Name() == "wailsjs" || d.Name() == "docs" || d.Name() == "assets" {
				return fs.SkipDir
			}
			return nil
		}
		name := d.Name()
		if !strings.HasSuffix(name, ".js") || strings.HasSuffix(name, ".test.js") {
			return nil
		}
		// The two dev-time test helpers are not shipped and describe the very
		// mistake this guard catches in their header comments.
		if name == "testhtml.js" || name == "testdom.js" {
			return nil
		}
		files = append(files, filepath.ToSlash(path))
		return nil
	})
	if err != nil {
		t.Fatalf("could not walk frontend/: %v", err)
	}
	if len(files) == 0 {
		t.Fatal("found no frontend/**/*.js modules to scan; this guard cannot work, " +
			"fix the walk or the layout")
	}
	return files
}

// lineOf reports the 1-based line number of a byte offset, so a failure points
// at a place the owner can open.
func lineOf(source string, offset int) int {
	return 1 + strings.Count(source[:offset], "\n")
}

func TestNoCamelCaseDataAttributeIsRendered(t *testing.T) {
	var offences []string

	for _, path := range frontendSourceFiles(t) {
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("could not read %s: %v", path, err)
		}
		source := string(raw)

		for _, m := range dataAttrRe.FindAllStringSubmatchIndex(source, -1) {
			name := source[m[2]:m[3]]
			if strings.ToLower(name) == name {
				continue
			}
			offences = append(offences, fmt.Sprintf(
				"%s:%d renders `data-%s`. A browser lower-cases attribute names, so "+
					"dataset.%s is undefined at runtime and the handler reading it does "+
					"nothing. Write `data-%s` and read `dataset.%s`.",
				path, lineOf(source, m[0]), name,
				name, dashCase(name), camelCase(dashCase(name))))
		}

		for _, m := range dataOptionRe.FindAllStringSubmatchIndex(source, -1) {
			body := source[m[2]:m[3]]
			for _, k := range dataOptionKeyRe.FindAllStringSubmatch(body, -1) {
				key := k[1]
				if strings.ToLower(key) == key {
					continue
				}
				offences = append(offences, fmt.Sprintf(
					"%s:%d passes `data: { %s: ... }`, which ui.js button() renders as "+
						"`data-%s`. A browser lower-cases attribute names, so dataset.%s is "+
						"undefined at runtime. Write `\"%s\"` as the key and read `dataset.%s`.",
					path, lineOf(source, m[0]), key,
					key, key, dashCase(key), camelCase(dashCase(key))))
			}
		}
	}

	sort.Strings(offences)
	for _, o := range offences {
		t.Error(o)
	}
}

// dashCase turns a camel-case attribute name into the spelling the DOM reads
// back as that same camel-case dataset key: "mainText" becomes "main-text".
func dashCase(name string) string {
	var out strings.Builder
	for i, r := range name {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				out.WriteByte('-')
			}
			out.WriteRune(r - 'A' + 'a')
			continue
		}
		out.WriteRune(r)
	}
	return out.String()
}

// camelCase is dashCase's inverse, i.e. the dataset key a dashed attribute name
// produces. Both directions are spelled out so the failure message can show the
// fix and the read side of it together.
func camelCase(name string) string {
	parts := strings.Split(name, "-")
	for i := 1; i < len(parts); i++ {
		if parts[i] == "" {
			continue
		}
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

// TestDashCaseAndCamelCaseAreInverses pins the pair the failure message relies
// on. A guard whose suggested fix is wrong sends the reader to the wrong place,
// which is how a guard gets deleted.
func TestDashCaseAndCamelCaseAreInverses(t *testing.T) {
	cases := []struct{ camel, dashed string }{
		{"mainText", "main-text"},
		{"groupType", "group-type"},
		{"withCategory", "with-category"},
		{"key", "key"},
	}
	for _, c := range cases {
		if got := dashCase(c.camel); got != c.dashed {
			t.Errorf("dashCase(%q) = %q, want %q", c.camel, got, c.dashed)
		}
		if got := camelCase(c.dashed); got != c.camel {
			t.Errorf("camelCase(%q) = %q, want %q", c.dashed, got, c.camel)
		}
	}
}
